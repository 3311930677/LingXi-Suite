function Rows($s) {
  @($s -split "`r?`n" | Where-Object { $_ -ne '' })
}

function ConvertTo-Rects([string[]]$rows, [hashtable]$pal, [string]$what, [bool]$full) {
  if ($full -and $rows.Count -ne $H) { throw "$what 行数 $($rows.Count) != $H" }
  if ($rows.Count -gt $H) { throw "$what 行数 $($rows.Count) 超出 $H" }
  $out = New-Object System.Text.StringBuilder
  $w0 = $rows[0].Length
  for ($yy = 0; $yy -lt $rows.Count; $yy++) {
    $r = $rows[$yy]
    if ($full -and $r.Length -ne $W) { throw "$what 第 $yy 行长度 $($r.Length) != $W : $r" }
    if (-not $full -and $r.Length -ne $w0) { throw "$what 第 $yy 行长度 $($r.Length) != $w0 : $r" }
    $x = 0
    while ($x -lt $r.Length) {
      $ch = [string]$r[$x]
      if ($ch -eq '.') { $x++; continue }
      if (-not $pal.ContainsKey($ch)) { throw "$what 未知字符 '$ch' @ ($x,$yy)" }
      $run = 1
      while ($x + $run -lt $r.Length -and [string]$r[$x + $run] -eq $ch) { $run++ }
      [void]$out.Append("<rect x=`"$x`" y=`"$yy`" width=`"$run`" height=`"1`" fill=`"$($pal[$ch])`"/>")
      $x += $run
    }
  }
  $out.ToString()
}

