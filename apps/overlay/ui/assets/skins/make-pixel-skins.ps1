function New-SkinSvg([string]$file, [hashtable]$pal, [string[]]$frameA, [string[]]$frameB, [double]$dur, $overlays, [bool]$shake) {
  $what = [IO.Path]::GetFileName($file)
  $a = ConvertTo-Rects $frameA $pal "$what/A" $true
  $b = ConvertTo-Rects $frameB $pal "$what/B" $true
  $ov = ''
  foreach ($ol in $overlays) {
    $r = ConvertTo-Rects $ol.rows $pal "$what/overlay@($($ol.x),$($ol.y))" $false
    $ov += "<g class=`"ov $($ol.cls)`" transform=`"translate($($ol.x),$($ol.y))`">$r</g>"
  }
  $css = $cssTemplate.Replace('__DUR__', ([string]$dur))
  $inner = "<g class=`"fa`">$a</g><g class=`"fb`">$b</g>"
  if ($shake) { $inner = "<g class=`"shake`">$inner</g>" }
  $svg = "<svg xmlns=`"http://www.w3.org/2000/svg`" viewBox=`"0 0 $W $H`" width=`"$W`" height=`"$H`" shape-rendering=`"crispEdges`">" +
    "<style>$css</style>$inner$ov</svg>"
  [IO.File]::WriteAllText($file, $svg)
  Write-Host "生成 $what ($([math]::Round((Get-Item $file).Length/1KB,1)) KB)"
}

